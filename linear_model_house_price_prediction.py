vif_df["VIF"] = [variance_inflation_factor(X.values, i) for i in range(X.shape[1])]
print(vif_df)

"""VIF is based on regressing each predictor against the remaining predictors. Including an intercept avoids distortions that can occur when regressions are forced through the origin. This provides a more reliable assessment of multicollinearity.

I evaluated multicollinearity using both a correlation matrix and Variance Inflation Factor (VIF). Initially, VIF values appeared unusually high. After reviewing the calculation methodology, I recomputed VIF using a model with an intercept term, which is the appropriate approach. The final VIF values ranged from 1.63 to 2.49, indicating low multicollinearity among the numerical predictors.

Residual Distribution (Error Distribution)
"""

residuals = y_test_actual - y_pred_actual

plt.figure(figsize=(8,5))

sns.histplot(
    residuals,
    kde=True
)

plt.title('Residual Distribution')
plt.xlabel('Residual')
plt.ylabel('Frequency')

plt.show()

"""I examined the residual distribution to verify whether prediction errors were approximately normally distributed. Most residuals were centered around zero, indicating the model was not systematically overpredicting or underpredicting house prices.

Q-Q Plot
"""

import scipy.stats as stats
plt.figure(figsize=(8,5))
stats.probplot(residuals,dist="norm",plot=plt)
