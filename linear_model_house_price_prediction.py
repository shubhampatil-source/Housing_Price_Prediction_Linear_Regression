"""I used a Q-Q plot to assess residual normality. Most observations aligned closely with the theoretical normal line, although slight deviations were observed in the tails, which is typical for real estate data.

Homoscedasticity Check
"""

plt.figure(figsize=(8,5))
sns.scatterplot(x=y_pred_actual,y=residuals)
